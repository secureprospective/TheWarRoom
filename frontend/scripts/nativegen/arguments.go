package main

import (
	"fmt"
	"strings"

	catalog "github.com/secureprospective/TheWarRoom/internal/commandcatalog"
)

func generateArguments(entries []catalog.Entry) []byte {
	var browser, desktop, workflow strings.Builder
	for _, entry := range entries {
		if c := entry.Browser; c != nil {
			fmt.Fprintf(&browser, "%q:\n %s;\n", entry.ID, c.Arguments.ClientType)
		}
		for _, d := range entry.Desktop {
			var args []string
			for _, f := range d.Binding.Arguments.Fields {
				args = append(args, tsShape(f.Schema))
			}
			fmt.Fprintf(&desktop, "%q: [\n%s\n];\n", d.Feature+"."+d.Command.Method, strings.Join(args, ",\n"))
		}
		if entry.Workflow != nil {
			fmt.Fprintf(&workflow, "%q: NativeArguments<%q>;\n", entry.ID, entry.ID)
		}
	}
	return []byte("// Code generated by nativegen -surface doors; DO NOT EDIT.\n" +
		"import type { NativeArguments, NativeCommandId } from './native';\n" +
		"import type { MFLArguments, MFLCommandId } from './mfl';\n" +
		"export type BrowserArgumentMap = {\n" + browser.String() + "};\n" +
		"export type BrowserArguments<K extends keyof BrowserArgumentMap> = BrowserArgumentMap[K];\n" +
		"export type DesktopArgumentMap = {\n" + desktop.String() + "};\n" +
		"export type WorkflowArgumentMap = {\n" + workflow.String() + "};\n" +
		"export type CommandArgumentMap = {\n native: { [K in NativeCommandId]: NativeArguments<K> };\n mfl: { [K in MFLCommandId]: MFLArguments<K> };\n browser: BrowserArgumentMap;\n wails: DesktopArgumentMap;\n workflow: WorkflowArgumentMap;\n};\n" +
		"export type CommandArguments<\n D extends keyof CommandArgumentMap, K extends keyof CommandArgumentMap[D]\n> = CommandArgumentMap[D][K];\n")
}

func tsShape(s catalog.Schema) string {
	var value string
	switch {
	case len(s.Enum) > 0:
		var choices []string
		for _, e := range s.Enum {
			choices = append(choices, fmt.Sprintf("%q", e))
		}
		value = strings.Join(choices, " |\n")
	case s.Type == "object":
		value = tsObject(s)
	case s.Type == "array" && s.Items != nil:
		value = "(" + tsShape(*s.Items) + ")[]"
	case s.Type == "map" && s.Items != nil:
		value = "Record<string, " + tsShape(*s.Items) + ">"
	case s.Type == "integer" || s.Type == "number":
		value = "number"
	case s.Type == "string" || s.Type == "boolean":
		value = s.Type
	default:
		value = "unknown"
	}
	if s.Nullable {
		value = "(" + value + ") | null"
	}
	return value
}

func tsObject(s catalog.Schema) string {
	var fields []string
	for _, f := range s.Fields {
		optional := ""
		if f.Optional {
			optional = "?"
		}
		fields = append(fields, fmt.Sprintf("%q%s: %s", f.Name, optional, tsShape(f.Schema)))
	}
	value := "Record<string, never>"
	if len(fields) > 0 {
		value = "{\n" + strings.Join(fields, ";\n") + "\n}"
	}

	return value
}
