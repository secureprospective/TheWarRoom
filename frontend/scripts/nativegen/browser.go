package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"os"

	"github.com/secureprospective/TheWarRoom/internal/app/catalog"
)

func generateBrowser(commands []catalog.BrowserCommand) ([]byte, error) {
	definitions := make(map[string]catalog.BrowserCommand, len(commands))
	for _, command := range commands {
		if _, exists := definitions[command.ID]; exists || command.ID == "" || command.Label == "" {
			return nil, fmt.Errorf("browser commands: missing or duplicate definition %q", command.ID)
		}
		definitions[command.ID] = command
	}
	body, err := json.MarshalIndent(definitions, "", "  ")
	if err != nil {
		return nil, fmt.Errorf("encode browser commands: %w", err)
	}
	return append(append([]byte("// Code generated by go run ./frontend/scripts/nativegen -surface browser; DO NOT EDIT.\nexport const browserCommands = "), body...), []byte(" as const;\n")...), nil
}

func runBrowser(path string, check bool) error {
	body, err := generateBrowser(catalog.BrowserCommands())
	if err != nil {
		return err
	}
	if check {
		held, err := os.ReadFile(path)
		if err != nil {
			return fmt.Errorf("read browser commands: %w", err)
		}
		if !bytes.Equal(held, body) {
			return fmt.Errorf("browser commands are stale; run go run ./frontend/scripts/nativegen -surface browser")
		}
		return nil
	}
	if err := os.WriteFile(path, body, 0o600); err != nil {
		return fmt.Errorf("write browser commands: %w", err)
	}
	return nil
}
