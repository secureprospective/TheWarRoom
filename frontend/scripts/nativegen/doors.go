package main

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"slices"
	"strings"

	catalog "github.com/secureprospective/TheWarRoom/internal/commandcatalog"
	"github.com/secureprospective/TheWarRoom/internal/composition"
)

func runDoors(root string, check bool) error {
	registry, err := composition.CommandRegistry()
	if err != nil {
		return fmt.Errorf("bind generation registry: %w", err)
	}
	files, err := generateDoors(registry)
	if err != nil {
		return err
	}
	for path, body := range files {
		path = filepath.Join(root, path)
		if check {
			held, err := os.ReadFile(path)
			if err != nil {
				return fmt.Errorf("read generated door %s: %w", path, err)
			}
			if !bytes.Equal(held, body) {
				return fmt.Errorf("stale command door %s; run go run ./frontend/scripts/nativegen -surface doors", path)
			}
		} else if err := os.WriteFile(path, body, 0o600); err != nil {
			return fmt.Errorf("write generated door: %w", err)
		}
	}
	return nil
}

func generateDoors(registry *catalog.Registry) (map[string][]byte, error) {
	if err := registry.Validate(); err != nil {
		return nil, fmt.Errorf("generate doors: %w", err)
	}
	var wails, cli, bar strings.Builder
	wails.WriteString("// Code generated by nativegen -surface doors; DO NOT EDIT.\npackage composition\n")
	cli.WriteString("// Code generated by nativegen -surface doors; DO NOT EDIT.\npackage main\nfunc generatedVerbs() []commandVerb { return []commandVerb{\n")
	bar.WriteString("// Code generated by nativegen -surface doors; DO NOT EDIT.\nexport const commandBarIds = [\n")
	features := map[string]bool{}
	var manifest []string
	for _, entry := range registry.Entries() {
		for _, d := range entry.Desktop {
			features[d.Feature] = true
			manifest = append(manifest, d.Feature+".API."+d.Command.Method)
		}
		if c := entry.Browser; c != nil {
			if len(c.Args) == 0 && c.Searchable {
				fmt.Fprintf(&bar, "%q,\n", c.ID)
			}
		}
		if entry.CLI {
			c := entry.Definition
			fmt.Fprintf(&cli, "{ID:%q, Label:%q, Modes:[]string{", entry.ID, entry.Label)
			for _, mode := range c.Modes {
				fmt.Fprintf(&cli, "%q,", mode)
			}
			cli.WriteString("}},\n")
		}
	}
	finishDoorSources(&wails, &cli, &bar, features)
	slices.Sort(manifest)
	wailsGo, err := format.Source([]byte(wails.String()))
	if err != nil {
		return nil, fmt.Errorf("format Wails surface: %w", err)
	}
	cliGo, err := format.Source([]byte(cli.String()))
	if err != nil {
		return nil, fmt.Errorf("format CLI verbs: %w", err)
	}
	reads, err := generateReadCommands(registry.Entries())
	if err != nil {
		return nil, err
	}
	return map[string][]byte{
		"internal/composition/wails_surface.gen.go":   wailsGo,
		"testdata/bindings/manifest.txt":              []byte(strings.Join(manifest, "\n") + "\n"),
		"cmd/twr/verbs.gen.go":                        cliGo,
		"frontend/src/app/commands/arguments.gen.ts":  generateArguments(registry.Entries()),
		"frontend/src/app/commands/reads.gen.ts":      reads,
		"frontend/src/app/commands/commandbar.gen.ts": []byte(bar.String()),
	}, nil
}

func finishDoorSources(wails, cli, bar *strings.Builder, features map[string]bool) {
	var names []string
	for name := range features {
		names = append(names, name)
	}
	slices.Sort(names)
	wails.WriteString("import (\n")
	for _, name := range names {
		fmt.Fprintf(wails, "%sapi %q\n", name, "github.com/secureprospective/TheWarRoom/internal/app/"+name)
	}
	wails.WriteString(")\ntype commandAPIs struct {\n")
	for _, name := range names {
		fmt.Fprintf(wails, "%s *%sapi.API\n", name, name)
	}
	wails.WriteString("}\nfunc generatedWailsBindings(apis commandAPIs) []interface{} { return []interface{}{\n")
	for _, name := range names {
		fmt.Fprintf(wails, "apis.%s,\n", name)
	}
	wails.WriteString("} }\n")
	cli.WriteString("} }\n")
	bar.WriteString("] as const;\n")
}
