// Command nativegen generates the native client's types and grammar from the Go catalog.
package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"os"
	"strings"

	"github.com/secureprospective/TheWarRoom/internal/app/catalog"
	app "github.com/secureprospective/TheWarRoom/internal/app/commissioner"
)

func main() {
	out := flag.String("out", "frontend/src/app/commands/native.gen.ts", "generated TypeScript file")
	check := flag.Bool("check", false, "refuse stale output without writing")
	flag.Parse()
	if err := run(*out, *check); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func run(path string, check bool) error {
	body, err := generate(app.NativeCommands())
	if err != nil {
		return err
	}
	if check {
		held, err := os.ReadFile(path)
		if err != nil {
			return fmt.Errorf("read generated native commands: %w", err)
		}
		if !bytes.Equal(held, body) {
			return fmt.Errorf("native commands are stale; run go run ./frontend/scripts/nativegen")
		}
		return nil
	}
	if err := os.WriteFile(path, body, 0o600); err != nil {
		return fmt.Errorf("write native commands: %w", err)
	}
	return nil
}

func generate(commands []catalog.Command) ([]byte, error) {
	published, err := catalog.Publication(commands)
	if err != nil {
		return nil, fmt.Errorf("generate native commands: %w", err)
	}
	var out strings.Builder
	out.WriteString("// Code generated by go run ./frontend/scripts/nativegen; DO NOT EDIT.\n")
	out.WriteString("export const nativeCommands = {\n")
	for _, command := range published {
		body, err := json.Marshal(command)
		if err != nil {
			return nil, fmt.Errorf("encode native command: %w", err)
		}
		fmt.Fprintf(&out, "%q: { definition: %s, phrase: %q },\n", command.ID, body, phrase(command.ID))
	}
	out.WriteString("} as const;\n")
	return []byte(out.String()), nil
}

func phrase(id string) string {
	words := strings.Split(strings.ReplaceAll(id, "_", " "), ".")
	for i, word := range words {
		switch word {
		case "commish":
			words[i] = "league"
		case "native":
			words[i] = "native league"
		case "auto":
			words[i] = "automatically"
		case "stats", "stat":
			words[i] = "statistics"
		case "cap":
			words[i] = "salary cap"
		case "whatsnew":
			words[i] = "news"
		}
	}
	if len(words) > 1 {
		words = append([]string{words[len(words)-1]}, words[:len(words)-1]...)
	}
	return strings.Join(words, " ")
}
