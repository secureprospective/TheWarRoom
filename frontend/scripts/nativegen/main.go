// Command nativegen generates the native client's types and grammar from the Go catalog.
package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"os"
	"strings"

	"github.com/secureprospective/TheWarRoom/internal/app/catalog"
	app "github.com/secureprospective/TheWarRoom/internal/app/commissioner"
	"github.com/secureprospective/TheWarRoom/internal/app/offers"
)

func main() {
	out := flag.String("out", "frontend/src/app/commands/native.gen.ts", "generated TypeScript file")
	check := flag.Bool("check", false, "refuse stale output without writing")
	surface := flag.String("surface", "native", "native or mfl catalog")
	flag.Parse()
	if *surface == "mfl" {
		if err := runMFL(*check); err != nil {
			fmt.Fprintln(os.Stderr, err)
			os.Exit(1)
		}
		return
	}
	if *surface != "native" {
		fmt.Fprintln(os.Stderr, "unknown catalog")
		os.Exit(1)
	}
	if err := run(*out, *check); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func run(path string, check bool) error {
	body, err := generate(app.NativeCommands())
	if err != nil {
		return err
	}
	if check {
		held, err := os.ReadFile(path)
		if err != nil {
			return fmt.Errorf("read generated native commands: %w", err)
		}
		if !bytes.Equal(held, body) {
			return fmt.Errorf("native commands are stale; run go run ./frontend/scripts/nativegen")
		}
		return nil
	}
	if err := os.WriteFile(path, body, 0o600); err != nil {
		return fmt.Errorf("write native commands: %w", err)
	}
	return nil
}

func generate(commands []catalog.Command) ([]byte, error) {
	published, err := catalog.Publication(commands)
	if err != nil {
		return nil, fmt.Errorf("generate native commands: %w", err)
	}
	var out strings.Builder
	out.WriteString("// Code generated by go run ./frontend/scripts/nativegen; DO NOT EDIT.\n")
	schemas := schemaTable{names: make(map[string]string)}
	var entries strings.Builder
	for _, command := range published {
		name, err := schemas.intern(command.Arguments)
		if err != nil {
			return nil, err
		}
		body, err := json.MarshalIndent(struct {
			catalog.Command
			Arguments string
		}{command, name}, "  ", "  ")
		if err != nil {
			return nil, fmt.Errorf("encode native command: %w", err)
		}
		definition := strings.Replace(string(body), `"Arguments": "`+name+`"`, `"Arguments": `+name, 1)
		fmt.Fprintf(&entries, "%q: {\n  definition: %s,\n  phrase: %q,\n},\n", command.ID, definition, phrase(command.ID))
	}
	out.WriteString(schemas.out.String())
	out.WriteString("export const nativeCommands = {\n")
	out.WriteString(entries.String())
	out.WriteString("} as const;\n")
	return []byte(out.String()), nil
}

// Identical subtrees share a literal constant, preserving TypeScript inference and runtime shape.
type schemaTable struct {
	names map[string]string
	out   strings.Builder
}

func (t *schemaTable) intern(schema catalog.Schema) (string, error) {
	body, err := json.Marshal(schema)
	if err != nil {
		return "", fmt.Errorf("encode native schema: %w", err)
	}
	key := string(body)
	if name, ok := t.names[key]; ok {
		return name, nil
	}
	var fields strings.Builder
	fields.WriteString("[\n")
	for i, field := range schema.Fields {
		name, err := t.intern(field.Schema)
		if err != nil {
			return "", err
		}
		if i > 0 {
			fields.WriteString(",\n")
		}
		fmt.Fprintf(&fields, "    {Name:%q,Optional:%t,Schema:%s}", field.Name, field.Optional, name)
	}
	fields.WriteString("\n  ]")
	items := "null"
	if schema.Items != nil {
		items, err = t.intern(*schema.Items)
		if err != nil {
			return "", err
		}
	}
	enum, err := json.MarshalIndent(schema.Enum, "  ", "  ")
	if err != nil {
		return "", fmt.Errorf("encode native choices: %w", err)
	}
	fieldList := fields.String()
	if schema.Fields == nil {
		fieldList = "null"
	}
	name := fmt.Sprintf("schema%d", len(t.names))
	t.names[key] = name
	fmt.Fprintf(&t.out, "const %s = {\n  Type:%q,\n  Enum:%s,\n  Format:%q,\n  Validator:%q,\n  Nullable:%t,\n  Fields:%s,\n  Items:%s,\n} as const;\n",
		name, schema.Type, enum, schema.Format, schema.Validator, schema.Nullable, fieldList, items)
	return name, nil
}

func phrase(id string) string {
	words := strings.Split(strings.ReplaceAll(id, "_", " "), ".")
	for i, word := range words {
		switch word {
		case "commish":
			words[i] = "league"
		case "native":
			words[i] = "native league"
		case "auto":
			words[i] = "automatically"
		case "stats", "stat":
			words[i] = "statistics"
		case "cap":
			words[i] = "salary cap"
		case "whatsnew":
			words[i] = "news"
		}
	}
	if len(words) > 1 {
		words = append([]string{words[len(words)-1]}, words[:len(words)-1]...)
	}
	return strings.Join(words, " ")
}

func runMFL(check bool) error {
	const path = "frontend/src/app/commands/mfl.gen.ts"
	body, err := generate(offers.MFLCommands())
	if err != nil {
		return err
	}
	body = bytes.Replace(body, []byte("export const nativeCommands"), []byte("export const mflCommands"), 1)
	if check {
		held, err := os.ReadFile(path)
		if err != nil {
			return fmt.Errorf("read MFL commands: %w", err)
		}
		if !bytes.Equal(held, body) {
			return fmt.Errorf("MFL commands are stale; run go run ./frontend/scripts/nativegen -surface mfl")
		}
		return nil
	}
	if err := os.WriteFile(path, body, 0o600); err != nil {
		return fmt.Errorf("write MFL commands: %w", err)
	}
	return nil
}
