package main

import (
	"encoding/json"
	"fmt"
	"slices"
	"strings"

	catalog "github.com/secureprospective/TheWarRoom/internal/commandcatalog"
)

// Legacy desktop declarations have no read mode. Opt in only audited held reads;
// gravity alone cannot distinguish a read from refresh or browser opening.
func generateReadCommands(entries []catalog.Entry) ([]byte, error) {
	selected := []string{
		"archive.TargetArchive", "comms.TargetComms", "draft.TargetDraftReports",
		"market.TargetMarketReports", "race.TargetRace",
		"control.TargetLeagueSettings", "control.TargetBylaws", "control.TargetAccounting", "control.TargetSiteNews",
		"contracts.TargetLineup", "trades.TargetTrades", "control.TargetAlerts",
		"commissioner.TargetNativeLineup",
		"offers.TargetPersonal", "offers.TargetOffers", "commissioner.TargetNativeDraft",
		"market.TargetAssetBoard", "now.TargetNow",
		"sources.TargetDataSources", "sources.TargetCrosswalk", "control.GetParams",
		"sources.TargetCacheScopes", "draft.TargetDraftLab", "market.TargetMarketLists", "market.TargetPickClock",
		"market.TargetMarketStretches", "market.TargetAssetProfile",
		"counterparties.TargetCounterparties", "counterparties.TargetCounterpartTeam", "research.TargetResearch",
	}
	found := map[string]bool{}
	var out strings.Builder
	out.WriteString("// Code generated by nativegen -surface doors; DO NOT EDIT.\nimport type { DesktopArgumentMap } from './arguments.gen';\nexport const readCommands = {\n")
	for _, entry := range entries {
		for _, d := range entry.Desktop {
			key := d.Feature + "." + d.Command.Method
			if !slices.Contains(selected, key) {
				continue
			}
			if d.Command.Gravity != "G0" || (len(d.Command.Modes) > 0 && (len(d.Command.Modes) != 1 || d.Command.Modes[0] != catalog.Read)) {
				return nil, fmt.Errorf("query adapter %s is not a held reading", key)
			}
			body, err := json.MarshalIndent(struct {
				Command   string         `json:"command"`
				Arguments catalog.Schema `json:"arguments"`
			}{entry.ID, d.Binding.Arguments}, "", "  ")
			if err != nil {
				return nil, fmt.Errorf("encode read adapter %s: %w", key, err)
			}
			fmt.Fprintf(&out, "%q: %s,\n", key, body)
			found[key] = true
		}
	}
	for _, key := range selected {
		if !found[key] {
			return nil, fmt.Errorf("query adapter %s is absent from registry", key)
		}
	}
	out.WriteString("} as const;\nexport type ReadCommandId = keyof typeof readCommands;\nexport type ReadArguments<K extends ReadCommandId> = DesktopArgumentMap[K];\n")
	return []byte(out.String()), nil
}
