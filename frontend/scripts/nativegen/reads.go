package main

import (
	"encoding/json"
	"fmt"
	"slices"
	"strings"

	catalog "github.com/secureprospective/TheWarRoom/internal/commandcatalog"
)

// The held-read catalog is every G0 desktop adapter the registry declares read-only: legacy
// adapters opt in with catalog.heldRead, shared reads carry their native read mode.
func generateReadCommands(entries []catalog.Entry) ([]byte, error) {
	var out strings.Builder
	out.WriteString("// Code generated by nativegen -surface doors; DO NOT EDIT.\nimport type { DesktopArgumentMap } from './arguments.gen';\nexport const readCommands = {\n")
	count := 0
	for _, entry := range entries {
		for _, d := range entry.Desktop {
			if d.Command.Gravity != "G0" || !slices.Equal(d.Command.Modes, []catalog.Mode{catalog.Read}) {
				continue
			}
			key := d.Feature + "." + d.Command.Method
			body, err := json.MarshalIndent(struct {
				Command   string         `json:"command"`
				Arguments catalog.Schema `json:"arguments"`
			}{entry.ID, d.Binding.Arguments}, "", "  ")
			if err != nil {
				return nil, fmt.Errorf("encode read adapter %s: %w", key, err)
			}
			fmt.Fprintf(&out, "%q: %s,\n", key, body)
			count++
		}
	}
	if count == 0 {
		return nil, fmt.Errorf("registry declares no held desktop reads")
	}
	out.WriteString("} as const;\nexport type ReadCommandId = keyof typeof readCommands;\nexport type ReadArguments<K extends ReadCommandId> = DesktopArgumentMap[K];\n")
	return []byte(out.String()), nil
}
