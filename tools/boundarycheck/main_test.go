package main

import (
	"bytes"
	"os"
	"path/filepath"
	"strings"
	"testing"
)

func boundaryFixture(t *testing.T, source string) string {
	t.Helper()
	root := t.TempDir()
	fixtureWrite(t, root, "internal/composition/adapter.go", source)
	fixtureWrite(t, root, "internal/app/core/state.go", "package core\n")
	fixtureWrite(t, root, "docs/architecture/boundary-adapters.tsv", "")
	return root
}

func fixtureWrite(t *testing.T, root, relative, content string) {
	t.Helper()
	path := filepath.Join(root, relative)
	if err := os.MkdirAll(filepath.Dir(path), 0o700); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(path, []byte(content), 0o600); err != nil {
		t.Fatal(err)
	}
}

func approveFixture(t *testing.T, root string) {
	t.Helper()
	var inventory bytes.Buffer
	if err := run(root, true, &inventory); err != nil {
		t.Fatal(err)
	}
	fixtureWrite(t, root, "docs/architecture/boundary-adapters.tsv", strings.ReplaceAll(inventory.String(), "\treview\n", "\tadapter\n"))
}

func TestBoundaryAllowsReviewedAdaptersAndCosmeticChanges(t *testing.T) {
	root := boundaryFixture(t, "package composition\nfunc adapter(resource *int) int { if resource == nil { return 0 }; return *resource }\n")
	approveFixture(t, root)
	var output bytes.Buffer
	if err := run(root, false, &output); err != nil {
		t.Fatal(err)
	}
	fixtureWrite(t, root, "internal/composition/adapter.go", "package composition\n// transport resource check\nfunc adapter(resource *int) int {\n\n if resource == nil {\n return 0\n }; return *resource\n}\n")
	if err := run(root, false, &output); err != nil {
		t.Fatal("cosmetic edit rejected", err)
	}
}

func TestBoundaryRejectsNewDecisionsInBothLayersAndCallbacks(t *testing.T) {
	for _, tc := range []struct{ path, source string }{
		{"internal/composition/policy.go", "package composition\nfunc policy(cap int) bool { return cap > 1 }"},
		{"internal/app/core/policy.go", "package core\nfunc policy() func(int) bool { return func(cap int) bool { if cap > 1 { return true }; return false } }"},
		{"internal/composition/policy.gen.go", "// Code generated by fake. DO NOT EDIT.\npackage composition\nfunc policy(cap int) bool { return cap > 1 }"},
	} {
		t.Run(tc.path, func(t *testing.T) {
			root := boundaryFixture(t, "package composition\n")
			fixtureWrite(t, root, tc.path, tc.source)
			err := run(root, false, &bytes.Buffer{})
			if err == nil || !strings.Contains(err.Error(), "new decision syntax") || !strings.Contains(err.Error(), tc.path) {
				t.Fatal(err)
			}
		})
	}
}

func TestBoundaryRejectsChangedPolicyAndRequiresRatchetRemoval(t *testing.T) {
	root := boundaryFixture(t, "package composition\nfunc legacy(cap int) bool { return cap > 1 }")
	approveFixture(t, root)
	fixtureWrite(t, root, "internal/composition/adapter.go", "package composition\nfunc legacy(cap int) bool { return cap > 2 }")
	if err := run(root, false, &bytes.Buffer{}); err == nil || !strings.Contains(err.Error(), "changed decision-bearing function") {
		t.Fatal(err)
	}
	fixtureWrite(t, root, "internal/composition/adapter.go", "package composition\n")
	if err := run(root, false, &bytes.Buffer{}); err == nil || !strings.Contains(err.Error(), "stale allowlist entry") {
		t.Fatal(err)
	}
	fixtureWrite(t, root, "docs/architecture/boundary-adapters.tsv", "")
	if err := run(root, false, &bytes.Buffer{}); err != nil {
		t.Fatal(err)
	}
}

func TestBoundaryInventoryIsNotAutomaticApproval(t *testing.T) {
	root := boundaryFixture(t, "package composition\nfunc policy(cap int) bool { return cap > 1 }")
	var inventory bytes.Buffer
	if err := run(root, true, &inventory); err != nil {
		t.Fatal(err)
	}
	fixtureWrite(t, root, "docs/architecture/boundary-adapters.tsv", inventory.String())
	if err := run(root, false, &bytes.Buffer{}); err == nil || !strings.Contains(err.Error(), "invalid allowlist row") {
		t.Fatal(err)
	}
}
